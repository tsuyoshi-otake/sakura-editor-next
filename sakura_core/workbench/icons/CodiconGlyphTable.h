// 二分探索の前提。生成器が壊れたら実行時ではなくコンパイル時に落とす。
static_assert(std::is_sorted(std::begin(kCodiconGlyphs), std::end(kCodiconGlyphs),
	[](const SCodiconGlyphEntry& lhs, const SCodiconGlyphEntry& rhs) noexcept { return lhs.name < rhs.name; }),
	"kCodiconGlyphs must stay sorted by name; FindCodiconGlyph binary-searches it.");

/*!
	@brief アイコン名から同梱 codicon.ttf のコードポイントを引く

	@retval std::nullopt この表に無い名前。上流 VS Code の `Codicon` にも無い名前は
	                     向こうでも解決できないので、呼び出し側は自分のフォールバックへ
	                     落ちてよい。
*/
[[nodiscard]] inline std::optional<wchar_t> FindCodiconGlyph(std::wstring_view name) noexcept
{
	const auto found = std::lower_bound(std::begin(kCodiconGlyphs), std::end(kCodiconGlyphs), name,
		[](const SCodiconGlyphEntry& entry, std::wstring_view key) noexcept { return entry.name < key; });
	if (found == std::end(kCodiconGlyphs) || found->name != name) return std::nullopt;
	return found->character;
}

