"""Generate the pinned Unicode default lowercase tables used by URI identity."""

import argparse
import hashlib
import sys
from pathlib import Path


UNICODE_VERSION = "17.0.0"
PINNED_SHA256 = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "SpecialCasing.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
}
DEFAULT_OUTPUT = (
    Path(__file__).resolve().parents[1] / "sakura_core/platform/uri/UnicodeLowercaseData.h"
)


def read_ucd(ucd_dir: Path) -> dict[str, str]:
    inputs = {}
    for filename, expected in PINNED_SHA256.items():
        data = (ucd_dir / filename).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise ValueError(f"{filename}: SHA-256 mismatch. Expected {expected}, got {actual}.")
        inputs[filename] = data

    texts = {filename: data.decode("utf-8") for filename, data in inputs.items()}
    for stem in ("SpecialCasing", "DerivedCoreProperties"):
        expected_header = f"# {stem}-{UNICODE_VERSION}.txt"
        if texts[f"{stem}.txt"].splitlines()[0] != expected_header:
            raise ValueError(f"{stem}.txt: expected first line {expected_header!r}.")
    return texts


def uncommented_fields(text: str):
    for line in text.splitlines():
        data = line.partition("#")[0].strip()
        if data:
            yield [field.strip() for field in data.split(";")]


def lowercase_mappings(
    texts: dict[str, str],
) -> tuple[list[tuple[int, int]], list[tuple[int, int, int, int]]]:
    simple = {}
    for line in texts["UnicodeData.txt"].splitlines():
        fields = line.split(";")
        if not fields[13]:
            continue
        scalar, lower = int(fields[0], 16), int(fields[13], 16)
        if scalar != lower:
            simple[scalar] = lower

    special = []
    for fields in uncommented_fields(texts["SpecialCasing.txt"]):
        value, lower, _, _, condition = fields[:5]
        if condition:
            continue
        scalar = int(value, 16)
        mapping = tuple(int(item, 16) for item in lower.split())
        if len(mapping) > 2:
            raise ValueError(f"SpecialCasing.txt: lowercase mapping for U+{scalar:04X} exceeds two scalars.")
        # A full mapping identical to the simple fallback needs no second row.
        if mapping == (simple.get(scalar, scalar),):
            continue
        simple.pop(scalar, None)
        if mapping != (scalar,):
            padded = mapping + (0,) * (2 - len(mapping))
            special.append((scalar, len(mapping), *padded))
    return sorted(simple.items()), sorted(special)


def property_ranges(text: str) -> dict[str, list[tuple[int, int]]]:
    ranges = {"Cased": [], "Case_Ignorable": []}
    for fields in uncommented_fields(text):
        span, name = fields[:2]
        if name in ranges:
            first, separator, last = span.partition("..")
            ranges[name].append((int(first, 16), int(last if separator else first, 16)))

    for name, entries in ranges.items():
        merged = []
        for first, last in sorted(entries):
            if merged and first <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(last, merged[-1][1]))
            else:
                merged.append((first, last))
        ranges[name] = merged
    return ranges


def render_table(name: str, width: int, rows: list[tuple]) -> str:
    lines = [f"inline constexpr std::uint32_t {name}[][{width}] = {{"]
    for row in rows:
        values = ", ".join(f"0x{value:04X}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def render_header(texts: dict[str, str]) -> bytes:
    simple, special = lowercase_mappings(texts)
    ranges = property_ranges(texts["DerivedCoreProperties.txt"])
    tables = (
        render_table("kSimpleLowercase", 2, simple),
        render_table("kSpecialLowercase", 4, special),
        render_table("kCased", 2, ranges["Cased"]),
        render_table("kCaseIgnorable", 2, ranges["Case_Ignorable"]),
    )
    body = "\n\n".join(tables) + "\n"
    body_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
    lines = [
        f"// Generated by tools/generate-unicode-lowercase-table.py from Unicode {UNICODE_VERSION}. Do not edit.",
        *(f"// {filename} sha256:{digest}" for filename, digest in PINNED_SHA256.items()),
        f"// Table body sha256:{body_hash}",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace platform::uri::unicode_lowercase_data {",
        "",
        f'inline constexpr char kUnicodeVersion[] = "{UNICODE_VERSION}";',
        "",
        "// BEGIN GENERATED TABLES",
        body.rstrip("\n"),
        "// END GENERATED TABLES",
        "",
        "} // namespace platform::uri::unicode_lowercase_data",
        "",
    ]
    return "\n".join(lines).encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd-dir", required=True, type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = render_header(read_ucd(args.ucd_dir))
        if args.check:
            current = args.output.read_bytes().replace(b"\r\n", b"\n")
            if current != generated:
                raise ValueError(f"{args.output}: generated lowercase tables are out of date.")
        else:
            args.output.write_bytes(generated)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
